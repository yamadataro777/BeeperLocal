from typing import AsyncIterator, Protocol
from ..models import Conversation, FetchBatch, SendResult, UnifiedMessage

class Connector(Protocol):
    async def list_conversations(self, limit: int = 100) -> list[Conversation]: ...
    async def fetch(self, limit: int = 50) -> FetchBatch: ...


class LiveTextConnector(Connector, Protocol):
    """Optional capabilities; existing history-only providers stay unchanged."""
    async def send_text(self, text: str) -> SendResult: ...
    def watch(self, *, timeout: int = 300, from_now: bool = False) -> AsyncIterator[UnifiedMessage]: ...
